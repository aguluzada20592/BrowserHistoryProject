from advanced_history import AdvancedBrowserHistory
browser = AdvancedBrowserHistory("google.com", max_capacity=5)
browser.visit("youtube.com")
browser.visit("github.com")
browser.visit("stackoverflow.com")
print("ORIGINAL HISTORY:")
browser.display_history()
print("\nDELETE YOUTUBE:")
browser.delete_url("youtube.com")
browser.display_history()
print("\nRESTORE YOUTUBE:")
browser.restore()
browser.display_history()
print("\nDELETE CURRENT PAGE:")
browser.delete_url("stackoverflow.com")
browser.display_history()
print("\nRESTORE CURRENT PAGE:")
browser.restore()
browser.display_history()